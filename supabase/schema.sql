-- ---------------------------------------------------------------------
-- Membres autorisés et rôles
-- Tout compte créé (par invitation) devient membre « user ».
-- Pour nommer un administrateur :
--   update public.members set role = 'admin' where email = 'prenom.nom@exemple.com';
-- ---------------------------------------------------------------------
create table public.members (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  email      text not null,
  role       text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create or replace function public.is_member() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members where user_id = auth.uid());
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members where user_id = auth.uid() and role = 'admin');
$$;

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.members (user_id, email) values (new.id, new.email)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------
-- Données de l'application
-- ---------------------------------------------------------------------

-- Modèle de colonnes (une seule ligne)
create table public.app_settings (
  id         int primary key default 1 check (id = 1),
  columns    jsonb not null default '[]',
  required   jsonb not null default '[]',
  date_col   int not null default -1,
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid()
);

-- Personnes proposées dans la liste d'affectation
create table public.people (
  name       text primary key,
  created_at timestamptz not null default now()
);

-- Sessions validées
create table public.sessions (
  id         text primary key,
  at         timestamptz not null,
  created_by uuid not null default auth.uid(),
  created_at timestamptz not null default now()
);

-- Tickets : session en cours (session_id vide) ou archivés (session_id renseigné)
create table public.tickets (
  id          text primary key,
  seq         bigint generated by default as identity,
  cells       jsonb not null default '[]',
  assignee    text,
  assigned_at date,
  session_id  text references public.sessions (id) on delete cascade,
  archived_at timestamptz,
  updated_at  timestamptz not null default now(),
  updated_by  uuid default auth.uid()
);
create index tickets_session_idx on public.tickets (session_id);
create index tickets_seq_idx on public.tickets (seq);

-- Journal des actions : ajout seulement, jamais modifié ni supprimé
create table public.audit_log (
  id         bigint generated always as identity primary key,
  at         timestamptz not null default now(),
  user_id    uuid,
  user_email text,
  action     text not null,
  details    jsonb not null default '{}'
);
create index audit_log_at_idx on public.audit_log (at desc);

-- Auteur et date de modification renseignés par la base
create or replace function public.touch_row() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end;
$$;
create trigger tickets_touch before update on public.tickets
  for each row execute function public.touch_row();
create trigger app_settings_touch before update on public.app_settings
  for each row execute function public.touch_row();

-- L'auteur d'une entrée du journal est toujours l'utilisateur connecté (impossible à falsifier)
create or replace function public.audit_stamp() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.at := now();
  new.user_id := auth.uid();
  new.user_email := (select email from public.members where user_id = auth.uid());
  return new;
end;
$$;
create trigger audit_log_stamp before insert on public.audit_log
  for each row execute function public.audit_stamp();

-- Traces automatiques côté base : suppression de session, modification du modèle
create or replace function public.audit_session_delete() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.audit_log (action, details)
  values ('session_supprimee', jsonb_build_object(
    'session_id', old.id,
    'at', old.at,
    'tickets', (select count(*) from public.tickets where session_id = old.id)
  ));
  return old;
end;
$$;
create trigger sessions_audit_delete before delete on public.sessions
  for each row execute function public.audit_session_delete();

create or replace function public.audit_settings_update() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.audit_log (action, details)
  values ('modele_modifie', jsonb_build_object('colonnes', new.columns, 'avant', old.columns));
  return new;
end;
$$;
create trigger app_settings_audit_update after update on public.app_settings
  for each row
  when (old.columns is distinct from new.columns
     or old.required is distinct from new.required
     or old.date_col is distinct from new.date_col)
  execute function public.audit_settings_update();

-- ---------------------------------------------------------------------
-- Droits d'accès (Row Level Security)
-- Sans compte membre connecté, aucune donnée n'est lisible.
-- ---------------------------------------------------------------------
alter table public.members      enable row level security;
alter table public.app_settings enable row level security;
alter table public.people       enable row level security;
alter table public.sessions     enable row level security;
alter table public.tickets      enable row level security;
alter table public.audit_log    enable row level security;

-- Membres : chacun voit sa ligne, l'admin voit tout. Gestion depuis le tableau de bord Supabase.
create policy members_select on public.members for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

-- Modèle de colonnes : lecture pour tous ; création au premier import ; modification réservée aux admins
create policy settings_select on public.app_settings for select to authenticated using (public.is_member());
create policy settings_insert on public.app_settings for insert to authenticated with check (public.is_member());
create policy settings_update on public.app_settings for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- Personnes
create policy people_select on public.people for select to authenticated using (public.is_member());
create policy people_insert on public.people for insert to authenticated with check (public.is_member());
create policy people_delete on public.people for delete to authenticated using (public.is_member());

-- Sessions : suppression par un admin, ou par son auteur dans les 24 h (pour « Annuler la validation »)
create policy sessions_select on public.sessions for select to authenticated using (public.is_member());
create policy sessions_insert on public.sessions for insert to authenticated
  with check (public.is_member() and created_by = auth.uid());
create policy sessions_delete on public.sessions for delete to authenticated
  using (public.is_admin() or (created_by = auth.uid() and created_at > now() - interval '24 hours'));

-- Tickets : les tickets archivés ne peuvent être supprimés que par un admin
create policy tickets_select on public.tickets for select to authenticated using (public.is_member());
create policy tickets_insert on public.tickets for insert to authenticated with check (public.is_member());
create policy tickets_update on public.tickets for update to authenticated
  using (public.is_member()) with check (public.is_member());
create policy tickets_delete on public.tickets for delete to authenticated
  using (public.is_admin() or (public.is_member() and session_id is null));

-- Journal : lecture et ajout pour les membres ; aucune modification ni suppression possible
create policy audit_select on public.audit_log for select to authenticated using (public.is_member());
create policy audit_insert on public.audit_log for insert to authenticated with check (public.is_member());

-- ---------------------------------------------------------------------
-- Mise à jour en direct entre utilisateurs
-- ---------------------------------------------------------------------
alter publication supabase_realtime add table public.tickets, public.sessions, public.people, public.app_settings;
